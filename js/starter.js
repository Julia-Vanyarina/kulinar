async function addStarterRecipes() {
  if (await DB.getMeta(STARTER_KEY, false)) return 0;
  const existing = new Set((await DB.all('recipes')).map((r) => r.title.trim().toLowerCase()));
  let added = 0;
  const now = Date.now();
  for (const [i, r] of STARTER_RECIPES.entries()) {
    if (existing.has(r.title.toLowerCase())) continue;
    await DB.put('recipes', { ...r, id: uid(), photos: [], created: now, updated: now - i });
    added++;
  }
  await DB.setMeta(STARTER_KEY, true);
  return added;
}
