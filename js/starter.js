async function addStarterRecipes() {
  if (await DB.getMeta(STARTER_KEY, false)) return 0;
  const existing = new Set((await DB.all('recipes')).map((r) => r.title.trim().toLowerCase()));
  let added = 0;
  const now = Date.now();
  for (const [i, r] of STARTER_RECIPES.entries()) {
    if (existing.has(r.title.toLowerCase())) continue;
    await DB.put('recipes', { ...r, id: uid(), photos: [], created: now, updated: now - i });
    added++;
  }
  await DB.setMeta(STARTER_KEY, true);
  return added;
}

// Исправления в уже добавленных рецептах
async function migrateRecipes() {
  if (await DB.getMeta('mig_banoffee_1_5', false)) return;
  for (const r of await DB.all('recipes')) {
    if (r.title === 'Банановый трайфл с карамелью (баноффи)' && +r.yieldCount === 3500 && r.yieldUnit === 'мл') {
      r.yieldCount = 10;
      r.yieldUnit = 'шт';
      r.portionSize = 350;
      r.portionUnit = 'мл';
      r.notes = (r.notes || '').replace('Выход — 3500 мл: 10 боксов по 350 мл или 14 креманок по 250 мл. Для 10 креманок по 250 мл поставь в пересчёте «На 2500 мл».', 'Выход — 10 шт по 350 мл (боксы 80×80×55 мм). Для креманок поставь в пересчёте «по 250 мл»: на 10 креманок граммы уменьшатся сами, а из полной граммовки выйдет 14 шт по 250 мл.');
      r.updated = Date.now();
      await DB.put('recipes', r);
      delete state.scale[r.id];
    }
  }
  await DB.setMeta('mig_banoffee_1_5', true);
}

