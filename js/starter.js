async function addBanoffeeParty() {
  if (await DB.getMeta('starter_banoffee_party_1_13', false)) return 0;
  const all = await DB.all('recipes');
  let added = 0;

  // 1) Оригинал: заменить примерную технологию на настоящую — только если её не правили вручную
  const orig = all.find((r) => r.title === BANOFFEE_TITLE);
  if (orig) {
    const OLD_STEPS = STARTER_RECIPES[0].steps;
    const norm = (t) => String(t || '').replace(/\s+/g, ' ').trim();
    const cur = (Array.isArray(orig.stepItems) && orig.stepItems.length) ? stepsToText(orig.stepItems) : orig.steps;
    let changed = false;
    if (norm(cur) === norm(OLD_STEPS)) {
      orig.steps = BANOFFEE_STEPS;
      orig.stepItems = parseStepsText(BANOFFEE_STEPS);
      changed = true;
    }
    if (/по общей схеме/.test(orig.notes || '')) { orig.notes = BANOFFEE_NOTES; changed = true; }
    if (!/шоколад/i.test(orig.ingredients || '')) { orig.ingredients = (orig.ingredients || '').trim() + '\n\nДля декора\nТёмный шоколад — 35 г'; changed = true; }
    if (changed) { orig.updated = Date.now(); await DB.put('recipes', orig); }
  }

  // 2) Вариация на 20 креманок
  if (!all.some((r) => r.title === BANOFFEE_PARTY_TITLE)) {
    const now = Date.now();
    await DB.put('recipes', { ...BANOFFEE_PARTY, stepItems: parseStepsText(BANOFFEE_PARTY.steps), id: uid(), photos: [], created: now, updated: now + 1 });
    added++;
  }
  await DB.setMeta('starter_banoffee_party_1_13', true);
  return added;
}
